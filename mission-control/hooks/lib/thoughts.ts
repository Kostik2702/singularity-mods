/** The thought of the day at `now` (UTC days), spread over the list so neighbouring days differ. */
export function thoughtFor(now: number): string {
  const day = Math.floor(now / 86_400_000)
  return THOUGHTS[(day * 37) % THOUGHTS.length] ?? THOUGHTS[0] ?? ''
}
